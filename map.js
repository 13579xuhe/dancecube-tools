// ======================= 增强的坐标匹配函数 =======================
function getCityByCoordinates(lng, lat) {
    if (typeof window.cityCoordinates === 'undefined') {
        console.warn('cityCoordinates 未加载，使用简化匹配');
        const simpleCity = getCityByCoordinatesSimple(lng, lat);
        if (simpleCity) {
            return { city: simpleCity, lng: lng, lat: lat };
        }
        return null;
    }

    const coords = window.cityCoordinates;
    let nearestCity = null;
    let minDistance = Infinity;
    let matchedType = '';

    // 第一步：精确匹配区县（距离15km内）
    for (const [city, coord] of Object.entries(coords)) {
        const [cityLng, cityLat] = coord;
        const dx = lng - cityLng;
        const dy = lat - cityLat;
        const distance = Math.sqrt(dx * dx * 111 * 111 + dy * dy * 111 * 111);

        const isDistrict = city.endsWith('区') || city.endsWith('县');

        if (isDistrict && distance < 15) {
            if (distance < minDistance) {
                minDistance = distance;
                nearestCity = city;
                matchedType = 'district';
            }
        }
    }

    // 如果找到区县，直接返回
    if (nearestCity && matchedType === 'district') {
        console.log(`📍 精确匹配到区县: ${nearestCity}，距离 ${minDistance.toFixed(0)}km`);
        return { city: nearestCity, lng: lng, lat: lat };
    }

    // 第二步：匹配地级市（距离25km内）
    for (const [city, coord] of Object.entries(coords)) {
        const [cityLng, cityLat] = coord;
        const dx = lng - cityLng;
        const dy = lat - cityLat;
        const distance = Math.sqrt(dx * dx * 111 * 111 + dy * dy * 111 * 111);

        const isCity = city.endsWith('市') && !city.endsWith('区');

        if (isCity && distance < 25) {
            if (distance < minDistance) {
                minDistance = distance;
                nearestCity = city;
                matchedType = 'city';
            }
        }
    }

    // 如果找到地级市，返回
    if (nearestCity && matchedType === 'city') {
        console.log(`📍 匹配到地级市: ${nearestCity}，距离 ${minDistance.toFixed(0)}km`);
        return { city: nearestCity, lng: lng, lat: lat };
    }

    // 第三步：全局搜索最近的城市
    for (const [city, coord] of Object.entries(coords)) {
        const [cityLng, cityLat] = coord;
        const dx = lng - cityLng;
        const dy = lat - cityLat;
        const distance = Math.sqrt(dx * dx * 111 * 111 + dy * dy * 111 * 111);

        if (distance < minDistance) {
            minDistance = distance;
            nearestCity = city;
            matchedType = 'any';
        }
    }

    // 放宽阈值
    let threshold = 200;
    if (nearestCity) {
        if (nearestCity.endsWith('区') || nearestCity.endsWith('县')) {
            threshold = 80;
        } else if (nearestCity.endsWith('市')) {
            threshold = 150;
        }
    }

    if (minDistance > threshold) {
        console.log(`📍 最近城市 ${nearestCity} 距离 ${minDistance.toFixed(0)}km，超过阈值 ${threshold}km`);
        // 使用简化匹配作为备选
        const simpleCity = getCityByCoordinatesSimple(lng, lat);
        if (simpleCity) {
            console.log(`📍 使用简化匹配: ${simpleCity}`);
            return { city: simpleCity, lng: lng, lat: lat };
        }
        return null;
    }

    console.log(`📍 最终匹配到: ${nearestCity}，距离 ${minDistance.toFixed(0)}km`);
    return { city: nearestCity, lng: lng, lat: lat };
}

